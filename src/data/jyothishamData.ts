function getUnrepeatedIndex(length: number, recentList: number[], maxHistory: number = 3): number {
  const available: number[] = [];
  for (let i = 0; i < length; i++) {
    if (!recentList.includes(i)) {
      available.push(i);
    }
  }
  const pool = available.length > 0 ? available : Array.from({ length }, (_, i) => i);
  const picked = pool[Math.floor(Math.random() * pool.length)];
  recentList.push(picked);
  if (recentList.length > maxHistory) {
    recentList.shift();
  }
  return picked;
}

export function getAstrologerById(id: AstrologerId): AstrologerProfile {
  return ASTROLOGERS.find((a) => a.id === id) || ASTROLOGERS[0];
}

export function getRandomSmileRoast(astrologerId: AstrologerId = 'unni'): string {
  const profile = getAstrologerById(astrologerId);
  const roasts = profile.smileRoasts && profile.smileRoasts.length > 0 ? profile.smileRoasts : UNNI_SMILE_ROASTS;
  const index = Math.floor(Math.random() * roasts.length);
  return roasts[index];
}

/**
 * Generate a complete, hilarious, non-repetitive Face Jathakam voiced by
 * the selected astrologer character based on real camera signals.
 */
export function generateFaceJyothisham(
  smileScore: number = 0,
  symmetryScore: number = 100,
  astrologerId: AstrologerId = 'unni'
): JyothishamPrediction {
  const astrologer = getAstrologerById(astrologerId);

  // 1. Pick non-repeating Archetype
  const availableArchetypes = ARCHETYPES.filter((a) => !recentArchetypeIds.includes(a.id));
  const archPool = availableArchetypes.length > 0 ? availableArchetypes : ARCHETYPES;
  const archetype = archPool[Math.floor(Math.random() * archPool.length)];
  recentArchetypeIds.push(archetype.id);
  if (recentArchetypeIds.length > 5) recentArchetypeIds.shift();

  // 2. Determine Smile Mood
  let smileMood: 'SERIOUS' | 'SUSPICIOUSLY HAPPY' | 'FUNNY' | 'ABSOLUTE CHAOS';
  let smileMoodMl: string;
  if (smileScore < 40) {
    smileMood = 'SERIOUS';
    smileMoodMl = 'ഗൗരവം (SERIOUS)';
  } else if (smileScore < 60) {
    smileMood = 'SUSPICIOUSLY HAPPY';
    smileMoodMl = 'സംശയാസ്പദമായ സന്തോഷം';
  } else if (smileScore < 80) {
    smileMood = 'FUNNY';
    smileMoodMl = 'തമാശ മോഡ്';
  } else {
    smileMood = 'ABSOLUTE CHAOS';
    smileMoodMl = 'അഴിഞ്ഞാട്ടം (CHAOS)';
  }

  // 3. Pick Categories without immediate repeats
  const career = CAREER_PREDICTIONS[getUnrepeatedIndex(CAREER_PREDICTIONS.length, recentCareerIdxs)];
  const money = MONEY_PREDICTIONS[getUnrepeatedIndex(MONEY_PREDICTIONS.length, recentMoneyIdxs)];
  const love = LOVE_PREDICTIONS[getUnrepeatedIndex(LOVE_PREDICTIONS.length, recentLoveIdxs)];
  const studies = STUDIES_PREDICTIONS[Math.floor(Math.random() * STUDIES_PREDICTIONS.length)];
  const future = FUTURE_PREDICTIONS[getUnrepeatedIndex(FUTURE_PREDICTIONS.length, recentFutureIdxs)];
  const todayProphecy = TODAYS_PROPHECIES[getUnrepeatedIndex(TODAYS_PROPHECIES.length, recentProphecyIdxs)];
  const nextEvent = NEXT_EVENTS[getUnrepeatedIndex(NEXT_EVENTS.length, recentNextEventIdxs)];

  // 4. Character-specific Astrologer Dosham & Remedy
  const unniDosham = UNNI_DOSHAMS[getUnrepeatedIndex(UNNI_DOSHAMS.length, recentDoshamIdxs)];
  const remedyItem = UNNI_REMEDIES[getUnrepeatedIndex(UNNI_REMEDIES.length, recentRemedyIdxs)];

  // Character-specific Speech Roast
  let characterSpeech = archetype.unniRoastMl;
  if (astrologerId === 'kumbidi' && archetype.kumbidiRoastMl) {
    characterSpeech = archetype.kumbidiRoastMl;
  } else if (astrologerId === 'yeshu' && archetype.yeshuRoastMl) {
    characterSpeech = archetype.yeshuRoastMl;
  }

  // 5. Derive luck percentage from visual signals
  const baseLuck = 50 + Math.floor(Math.random() * 38);
  const luck = Math.min(99, Math.max(12, Math.round(baseLuck * 0.7 + (smileScore * 0.3))));

  // 6. Generate ridiculous fake biometrics
  const faceEnergy = Math.min(99, Math.max(35, Math.round(40 + Math.random() * 45 + (smileScore * 0.15))));
  const smilePower = Math.min(100, Math.max(5, Math.round(smileScore)));
  const dramaLevel = Math.min(99, Math.max(40, Math.round(50 + Math.random() * 45)));
  const procrastination = Math.min(99, Math.max(60, Math.round(75 + Math.random() * 24)));
  const luckMetric = luck;
  const mainCharacter = Math.min(99, Math.max(30, Math.round(55 + (symmetryScore > 80 ? 25 : 10) + Math.random() * 15)));

  // 7. Confidence Box
  const confidenceValues = ['98.4%', '99.1%', '97.8%', '99.9%', '96.9%'];
  const confidence = confidenceValues[Math.floor(Math.random() * confidenceValues.length)];

  return {
    id: `jathakam-${Date.now()}`,
    astrologerId: astrologer.id,
    astrologerName: astrologer.name,
    astrologerTitle: astrologer.movieTitle,
    archetype,
    career: career.ml,
    careerEn: career.en,
    money: money.ml,
    moneyEn: money.en,
    love: love.ml,
    loveEn: love.en,
    studies,
    luck,
    future,
    todayProphecy,
    nextEvent,
    confidence,
    scientificBasis: `NONE. ${astrologer.name} സാക്ഷ്യം`,
    accuracyGuarantee: `0% (${astrologer.name} പറഞ്ഞാൽ പറഞ്ഞതാണ്)`,
    smileMood,
    smileMoodMl,
    smileScoreAtScan: Math.round(smileScore),
    unniSpeech: characterSpeech,
    unniDosham,
    unniRemedy: remedyItem.remedy,
    unniDakshina: remedyItem.dakshina,
    fakeMetrics: {
      faceEnergy,
      smilePower,
      dramaLevel,
      procrastination,
      luckMetric,
      mainCharacter,
    },
  };
}
